const calculator = {
    add: function(a, b) {
        return a + b;
    },
    sub: function(a, b) {
        return a - b;
    },
    mul: function(a, b) {
        return a * b;
    }
};



console.log(calculator.add(1, 2)); // Output: 3
console.log(calculator.sub(10, 4)); // Output: 6
console.log(calculator.mul(5, 5));  // Output: 25